/** Generate docs/rule-reference.md from the rule catalog. `--check` fails if it is stale. */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { RULES, RULES_VERSION } from '../dist/index.js';

const CATEGORY = {
  N: 'Protocol invalidity',
  A: 'Authorization',
  P: 'Privacy or security risk',
  U: 'Uncertainty',
  O: 'Operational',
};
const lines = [
  '# Rule reference',
  '',
  `<!-- Generated by tools/gen-rule-reference.mjs from src/rules/catalog.ts. Do not edit by hand. -->`,
  '',
  `Rules version ${RULES_VERSION}. Rule IDs are stable public API: they are never renamed or reused. Run \`eudi-disclosure explain <RULE_ID>\` for the same text in a terminal.`,
  '',
  'Categories: ' +
    Object.entries(CATEGORY)
      .map(([k, v]) => `**${k}** ${v.toLowerCase()}`)
      .join(' · ') +
    '.',
  '',
  '| Rule | Category | Outcome |',
  '| --- | --- | --- |',
  ...Object.values(RULES).map(
    (r) => `| [\`${r.id}\`](#${r.id.toLowerCase()}) | ${r.category} | ${r.outcome} |`,
  ),
  '',
];
for (const r of Object.values(RULES)) {
  lines.push(
    `## ${r.id}`,
    '',
    `**${r.title}.** ${CATEGORY[r.category]} (${r.category}).`,
    '',
    `**Outcome:** ${r.outcome}`,
    '',
    r.description,
    '',
    `**Fix:** ${r.remediation}`,
    '',
  );
  if (r.standardRefs.length > 0) lines.push(`**References:** ${r.standardRefs.join('; ')}`, '');
}
const text = lines.join('\n');
const path = join(import.meta.dirname, '..', 'docs', 'rule-reference.md');
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== text) {
    console.error(
      'docs/rule-reference.md is stale. Run: pnpm build && node tools/gen-rule-reference.mjs',
    );
    process.exit(1);
  }
  console.log('docs/rule-reference.md is current.');
} else {
  writeFileSync(path, text);
}
